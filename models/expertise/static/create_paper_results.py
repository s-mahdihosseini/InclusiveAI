def trim_xyw(x: np.ndarray, w: np.ndarray, x_min: float = 10.0, x_max: float = 14.0):
    x = np.asarray(x, float)
    w = np.asarray(w, float)
    mask = np.isfinite(x) & np.isfinite(w) & (w > 0) & (x >= x_min) & (x <= x_max)
    x = x[mask]
    w = w[mask]
    if x.size:
        w = w / w.sum()
    return x, w


def weighted_kde(x: np.ndarray, w: np.ndarray, grid: np.ndarray, bw_adjust: float = 1.3) -> np.ndarray:
    w = np.asarray(w, float)
    w = w / w.sum()
    kde = gaussian_kde(np.asarray(x, float), weights=w)
    kde.set_bandwidth(kde.factor * bw_adjust)
    return kde(grid)


