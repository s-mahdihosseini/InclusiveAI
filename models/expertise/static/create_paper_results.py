def validate_table3(table3: pd.DataFrame) -> list[str]:
    messages = []
    cols = ["Var(log w)", "p10", "p50", "p90", "p90 - p10", "p50 - p10", "p90 - p50"]
    for _, row in table3.iterrows():
        scenario = row["Scenario"]
        expected = PAPER_TABLE3_EXPECTED.get(scenario)
        if expected is None:
            messages.append(f"Unexpected Table 3 scenario: {scenario}")
            continue
        actual = row[cols].to_numpy(dtype=float)
        if not np.allclose(np.round(actual, 3), np.array(expected), atol=0.0005):
            messages.append(
                f"Table 3 mismatch for {scenario}: rounded actual "
                f"{np.round(actual, 3).tolist()} expected {expected}"
            )
    if not messages:
        messages.append("Table 3 values match the paper to three decimals.")
    return messages


