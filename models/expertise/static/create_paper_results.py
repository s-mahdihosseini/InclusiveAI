def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Create only the static-model results used in Paper.pdf.")
    parser.add_argument("--data", type=Path, default=DEFAULT_DATA_PATH, help="Path to Counterfactual.dta.")
    parser.add_argument("--outdir", type=Path, default=DEFAULT_OUTDIR, help="Output folder.")
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    data_path = args.data.resolve()
    outdir = args.outdir.resolve()
    outdir.mkdir(parents=True, exist_ok=True)

    configure_style()
    df_raw, raw_rows, clipped_f_counts = load_clean_data(data_path)
    results, diagnostics = compute_counterfactuals(df_raw, raw_rows, clipped_f_counts)

