def save_binsreg_source(result, outdir: Path, stem: str) -> None:
    parts = {
        "dots": getattr(result, "dots", None),
        "line": getattr(result, "line", None),
        "ci": getattr(result, "ci", None),
        "cb": getattr(result, "cb", None),
    }
    for name, frame in parts.items():
        if isinstance(frame, pd.DataFrame) and not frame.empty:
            frame.to_csv(outdir / f"{stem}_{name}.csv", index=False)


def add_binsreg_panel(ax, result, x_label: str, y_label: str, title: str, annotation: str) -> None:
    dots = result.dots
    line = result.line
    ax.scatter(dots["x"], dots["fit"], s=38, edgecolor="k", linewidth=0.3, zorder=3)
    ax.plot(line["x"], line["fit"], linewidth=1.5)
    if hasattr(result, "cb") and isinstance(result.cb, pd.DataFrame) and not result.cb.empty:
        ax.fill_between(result.cb["x"], result.cb["cb_l"], result.cb["cb_r"], alpha=0.12)
    ax.axhline(0, color="0.45", linewidth=0.8, linestyle="--")
    ax.set_xlabel(x_label)
    ax.set_ylabel(y_label)
    ax.set_title(title, fontsize=11)
    ax.annotate(
        annotation,
        xy=(0.97, 0.05),
        xycoords="axes fraction",
        ha="right",
        va="bottom",
        bbox=dict(boxstyle="round,pad=0.3", fc="white", ec="0.7"),
        fontsize=8,
    )


